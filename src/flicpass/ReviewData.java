package flicpass;

public class ReviewData {
    String username;
    String reviewerType;
    String rating;
    String reviewText;

    public ReviewData(String username, String reviewerType, String rating, String reviewText) {
        this.username = username;
        this.reviewerType = reviewerType;
        this.rating = rating;
        this.reviewText = reviewText;
    }
}

